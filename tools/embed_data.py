#!/usr/bin/env python3
"""data/game-data.json -> data/game-data.fallback.js

The site fetches data/game-data.json at runtime. When index.html is opened
directly from disk (file://) the browser blocks that fetch, so the page falls
back to this generated snapshot. Run this script after every JSON update.

    python3 tools/embed_data.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "game-data.json"
DST = ROOT / "data" / "game-data.fallback.js"

def main() -> int:
    try:
        data = json.loads(SRC.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print(f"[embed_data] invalid JSON: {exc}", file=sys.stderr)
        return 1
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=False)
    header = (
        "/* AUTO-GENERATED by tools/embed_data.py — do not edit by hand.\n"
        "   Offline snapshot used only when data/game-data.json cannot be fetched\n"
        "   (for example when index.html is opened via file://). */\n"
    )
    DST.write_text(f"{header}window.__OGG_DATA__ = {payload};\n", encoding="utf-8")
    print(f"[embed_data] wrote {DST.relative_to(ROOT)} ({DST.stat().st_size:,} bytes)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
